-- Standalone Duty Slips module for Sachin Enterprises.
-- Safe to run once; IF NOT EXISTS preserves existing data and objects.
create table if not exists public.duty_slips (
  id bigint generated by default as identity primary key,
  slip_number text not null unique,
  duty_date date not null default current_date,
  client_name text not null,
  booked_by text,
  client_phone text,
  reference_number text,
  duty_type text,
  destination text,
  guest_name text,
  guest_phone text,
  reporting_address text,
  vehicle_name text,
  vehicle_registration text,
  driver_name text,
  driver_phone text,
  start_km numeric(12,2),
  start_at timestamp,
  end_km numeric(12,2),
  end_at timestamp,
  total_km numeric(12,2) not null default 0,
  total_hours numeric(12,2) not null default 0,
  toll_amount numeric(12,2) not null default 0,
  parking_amount numeric(12,2) not null default 0,
  cash_advance numeric(12,2) not null default 0,
  next_requirement text,
  remarks text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists duty_slips_duty_date_idx on public.duty_slips (duty_date desc);
create index if not exists duty_slips_client_name_idx on public.duty_slips (client_name);
alter table public.duty_slips enable row level security;

drop policy if exists "Admin can view duty slips" on public.duty_slips;
drop policy if exists "Admin can create duty slips" on public.duty_slips;
drop policy if exists "Admin can update duty slips" on public.duty_slips;
drop policy if exists "Admin can delete duty slips" on public.duty_slips;

